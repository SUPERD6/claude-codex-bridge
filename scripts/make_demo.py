"""Regenerate docs/assets/demo.svg: a short animated terminal session (route -> run -> verify).

    python scripts/make_demo.py

The session is real ccx output, run against the stand-in CLIs in tests/fakes with a throwaway hub, so it can be
re-made at any time without spending tokens; the numbers are the stand-ins', and the frame says so."""
from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FAKES = ROOT / "tests" / "fakes"
OUT = ROOT / "docs" / "assets" / "demo.svg"


def session() -> list[tuple[str, str]]:
    """[(kind, text)] where kind is cmd | out | ok | dim."""
    with tempfile.TemporaryDirectory() as d:
        t = Path(d)
        for sub in ("hub", "codex", "claude", "work"):
            (t / sub).mkdir()
        (t / "work" / "README.md").write_text("# my-project\n", encoding="utf-8")
        env = {**os.environ, "CCX_HUB": str(t / "hub"), "CODEX_HOME": str(t / "codex"),
               "CLAUDE_CONFIG_DIR": str(t / "claude"), "CCX_CONFIG": str(t / "cfg.toml"),
               "CCX_CODEX_BIN": str(FAKES / "fake_codex.py"), "CCX_CLAUDE_BIN": str(FAKES / "fake_claude.py"),
               "CCX_AB_RATE": "0", "PYTHONUTF8": "1"}
        for k in ("CLAUDECODE", "CLAUDE_CODE_SESSION_ID", "CODEX_THREAD_ID", "CCX_DEPTH"):
            env.pop(k, None)

        def ccx(*args: str) -> dict:
            r = subprocess.run([sys.executable, str(ROOT / "ccx.py"), *args], cwd=t / "work", env=env,
                               capture_output=True, text=True, encoding="utf-8")
            if r.returncode not in (0, 2):
                raise SystemExit(f"ccx {' '.join(args)} failed:\n{r.stdout}\n{r.stderr}")
            return json.loads(r.stdout)

        ccx("init")
        route = ccx("route", "--to", "codex", "--b", "2")
        run = ccx("run", "--from", "claude", "--to", "codex", "--b", "2",
                  "--mode", "write", "--check", "python -c pass", "Add a slugify() helper with a test")
        rec = json.loads((t / "hub" / "ccx" / "runs" / run["run_id"] / "run.json").read_text(encoding="utf-8"))
        ccx("verify", run["run_id"], "--ok", "1")
    a = rec["attempts"][-1]
    tok = run["tokens"]
    return [
        ("cmd", "ccx route --to codex --b 2"),
        ("out", f"  {route['rung']}   p {route['p']:.2f} · with escalation {route.get('chain_p', route['p']):.2f}"),
        ("gap", ""),
        ("cmd", 'ccx run --to codex --b 2 --check "pytest -q" "Add a slugify() helper with a test"'),
        ("out", f"  claude → codex   {a['model']}/{a['effort']} · {len(rec['attempts'])} attempt"),
        ("ok", f"  status   {run['status']} · files {', '.join(run.get('files_changed') or [])}"),
        ("ok", f"  check    rerun by ccx: {'passed' if (run.get('check') or {}).get('passed') else 'FAILED'}"),
        ("out", f"  tokens   {tok['input'] + tok['cached']:,} in · {tok['output']} out · ${a.get('ae_usd') or 0:.4f}"),
        ("gap", ""),
        ("cmd", f"ccx verify {run['run_id']} --ok 1"),
        ("ok", "  ✓ recorded — routing learns from it (no verdict in 12 h: ccx records a probable one)"),
    ]


def svg(lines: list[tuple[str, str]]) -> str:
    W, top, step, per = 920, 74, 26, 0.9          # px; seconds between lines
    color = {"cmd": "#d9dee5", "out": "#aab3bf", "ok": "#58c27a", "gap": "#aab3bf"}
    H = top + step * len(lines) + 30
    total = per * len(lines) + 4                      # hold the full screen 4 s, then loop
    rows, n = [], 0
    for i, (kind, text) in enumerate(lines):
        if kind == "gap":
            continue
        y = top + i * step
        start = per * n / total * 100
        n += 1
        prompt = '<tspan fill="#7f8996">$ </tspan>' if kind == "cmd" else ""
        rows.append(f'<text x="28" y="{y}" fill="{color[kind]}" style="animation-name:k{n}">{prompt}{escape(text)}</text>')
        rows.append(f'<style>@keyframes k{n}{{0%,{start:.2f}%{{opacity:0}}{start + 0.5:.2f}%,97%{{opacity:1}}100%{{opacity:0}}}}</style>')
    return f"""<svg xmlns="http://www.w3.org/2000/svg" xml:space="preserve" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-labelledby="t d">
  <title id="t">ccx demo: route, run, check, verify</title>
  <desc id="d">An animated terminal: ccx picks a model for a task, runs it on Codex, reruns the check, and records the verdict. Generated by scripts/make_demo.py with stand-in CLIs.</desc>
  <style>
    text{{font-family:ui-monospace,SFMono-Regular,"Cascadia Mono",Menlo,Consolas,monospace;font-size:15px;white-space:pre;
          opacity:0;animation-duration:{total:.1f}s;animation-iteration-count:infinite;animation-timing-function:step-end}}
    .static{{opacity:1;animation:none}}
    @media (prefers-reduced-motion: reduce){{text{{opacity:1;animation:none}}}}
  </style>
  <rect width="{W}" height="{H}" rx="12" fill="#11161c"/>
  <circle cx="26" cy="24" r="6" fill="#3b434d"/><circle cx="46" cy="24" r="6" fill="#3b434d"/><circle cx="66" cy="24" r="6" fill="#3b434d"/>
  <text class="static" x="{W - 24}" y="29" text-anchor="end" fill="#7f8996" font-size="13">demo · stand-in CLIs · scripts/make_demo.py</text>
  <line x1="0" y1="44" x2="{W}" y2="44" stroke="#222a33"/>
  {chr(10).join('  ' + r for r in rows).strip()}
</svg>
"""


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(svg(session()), encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
